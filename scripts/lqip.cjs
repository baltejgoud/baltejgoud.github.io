/**
 * Writes src/content/lqip.ts: tiny blurred previews of the hero art, inlined so the first paint shows
 * the painting's colours instead of an empty block. Run after changing any hero image.
 */
const fs = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

const root = path.join(__dirname, "..");
const images = {
  valley: "public/assets/portfolio-valley.webp",
  valleyMobile: "public/assets/portfolio-valley-mobile.webp",
};

async function preview(file) {
  const buffer = await sharp(path.join(root, file)).resize(32).blur(1.2).webp({ quality: 45 }).toBuffer();
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

(async () => {
  const entries = [];
  for (const [key, file] of Object.entries(images)) entries.push(`  ${key}: "${await preview(file)}",`);
  const out = `// Generated by scripts/lqip.cjs. Do not edit by hand.\nexport const lqip = {\n${entries.join("\n")}\n} as const;\n`;
  fs.writeFileSync(path.join(root, "src/content/lqip.ts"), out);
  console.log(`lqip: wrote ${entries.length} previews`);
})();
